static std::array<PinChange::RegisteredPin, 1> registeredPins;
static std::chrono::duration<uint32_t, std::milli> debounceTime(minCycleTime);

// TODO: move button timing to its own file
template<typename TickType>
class ButtonTime
{
public:
    ButtonTime(TickType (*getTime)())
      : getTime(getTime)
    {
    }

    void irq()
    {
        TickType time = getTime();
        last_diff = time - last_time;
        last_time = time;
    }
    auto getDiff() -> TickType { return last_diff; }

private:
    TickType (*getTime)();
    volatile TickType last_time;
    volatile TickType last_diff;
};

extern "C" void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    PinChange::irq_dispatch(registeredPins, GPIO_Pin);
}

using Millis = std::chrono::duration<uint32_t, std::milli>;

static auto get_tick() -> Millis
{
    return Millis(HAL_GetTick());
}

auto main() -> int
{
    HAL_Init();

    SystemClock_Config();

    MX_GPIO_Init();
    HAL_NVIC_SetPriority(EXTI15_10_IRQn, 5, 0); // Lower priority than system
    HAL_NVIC_EnableIRQ(EXTI15_10_IRQn);
    MX_DMA_Init();
    MX_DAC_Init();
    MX_TIM2_Init();
    MX_TIM3_Init();
    MX_USART3_UART_Init();

    // Button press
    // TODO move to its own file
    DebouncedButtonEdge<std::chrono::duration<uint32_t, std::milli>>
      tempoButton(
        registeredPins,
        USER_Btn_Pin,
        []() -> std::chrono::duration<uint32_t, std::milli> {
            return std::chrono::duration<uint32_t, std::milli>(HAL_GetTick());
        },
        debounceTime);
    ButtonTime buttonTime(HAL_GetTick);
    assert_param(tempoButton.isRegistered());
    tempoButton.registerEdgeCallback(
      [&buttonTime]() -> void { buttonTime.irq(); });

    // Task to keep DAC on track
    auto waveform = SineWavetable<ComputationType, 1024>(computationMin / 2.0f,
                                                         computationMax / 2.0f);
    WavetableOsc osc(waveform.data);
    osc.setFrequency(100, 96000);
    std::array<ComputationType, computationBufferSize> inputBuffer{};

    Dac dac(inputBuffer);
    Dac::init();
    auto writeWaveform = [&osc, &inputBuffer, &dac]() -> void {
        if (dac.isReady()) {
            osc.increment(inputBuffer);
        }
        dac.execute();
    };

    // Create LED handlers
    auto led1 = Led<TIM_HandleTypeDef>(
      &htim3, TIM_CHANNEL_3, MX_TIM3_Init, MX_TIM3_DeInit);
    auto led2 = Led<GPIO_TypeDef>(LD2_GPIO_Port, LD2_Pin);
    auto led3 = Led<GPIO_TypeDef>(LD3_GPIO_Port, LD3_Pin);

    // Create LED tasks
    auto led1Breathe =
      LedBreatheAnimation(&led1, get_tick, Millis(cycleTimeMs));
    auto led2Toggle = LedToggleAnimation(&led2);
    auto led3Toggle = LedToggleAnimation(&led3);

    auto buttonToLed = [&led1Breathe, &buttonTime]() -> void {
        // Lambda sets period based on button interrupt
        if (buttonTime.getDiff() > minCycleTime &&
            buttonTime.getDiff() < maxCycleTime) {
            led1Breathe.setPeriod(std::chrono::duration<uint32_t, std::milli>(
              buttonTime.getDiff()));
        }
    };

    // Organize tasks in priority list
    // TODO: why do we need to explicitly cast lambdas to
    // not crash?
    std::array<std::unique_ptr<TaskControlBlockInterface<Millis>>, 6> tasks = {
        std::make_unique<TaskControlBlock<Millis, decltype(writeWaveform)>>(
          writeWaveform,
          []() -> Millis { return Millis(HAL_GetTick()); },
          Millis(1),
          Millis(0)),
        std::make_unique<TaskControlBlock<Millis, LedBreatheAnimation>>(
          led1Breathe,
          []() -> Millis { return Millis(HAL_GetTick()); },
          Millis(20),
          Millis(0)),
        std::make_unique<TaskControlBlock<Millis, LedToggleAnimation>>(
          led2Toggle,
          []() -> Millis { return Millis(HAL_GetTick()); },
          Millis(800),
          Millis(0)),
        std::make_unique<TaskControlBlock<Millis, LedToggleAnimation>>(
          led3Toggle,
          []() -> Millis { return Millis(HAL_GetTick()); },
          Millis(600),
          Millis(0)),
        std::make_unique<TaskControlBlock<Millis, void (*)()>>(
          task_print_logs,
          []() -> Millis { return Millis(HAL_GetTick()); },
          Millis(100),
          Millis(0)),
        std::make_unique<TaskControlBlock<Millis, decltype(buttonToLed)>>(
          buttonToLed,
          []() -> Millis { return Millis(HAL_GetTick()); },
          Millis(5),
          Millis(1))
    };

    // Run tasks, do not return
    scheduler(tasks);
}
